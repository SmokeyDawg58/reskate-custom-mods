"""Bake skate.'s Skatepedia trick inputs into Extension/Modes/skatepedia_inputs.h.

Input: a folder of `reskate_cli ebx-values <game-root> gameplay/skatepedia/tricks/skatepediaentry_<x>`
dumps, one per entry (any file name). Each SkatepediaEntry lists TrickInputs; input 0 is a regular
stance's or a goofy one's, in no fixed order (later inputs are the simplified controls). A step is
either the game's own image markup ("[img {0}]FLICKIT_Kickflip_RS[/img]", the flick-it stick
picture the Skatepedia card draws) or a localisation key ("ID_SKATEPEDIA_INAIR").

R.E.S.K.A.T.E. shows the steps of the trick that was set, so everyone knows how to copy it.

usage: python bake_skatepedia_inputs.py <dump folder> <output header>
"""
import pathlib, re, sys

source, output = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
entries = {}
for dump in sorted(source.glob('*.txt')):
    text = dump.read_text(encoding='utf-8', errors='replace')
    name = re.search(r'Name = "Gameplay/Skatepedia/Tricks/SkatepediaEntry_([^"]+)"', text, re.I)
    if not name or 'TrickInputs [' not in text:
        continue
    inputs = []
    block = text.split('TrickInputs [', 1)[1].split('SelectedTrickInputIndexDelegate', 1)[0]
    for part in re.split(r'\n    \[\d+\] \{', block)[1:]:
        steps = re.findall(r'\[\d+\] = "([^"]*)"', part.split('PIA [', 1)[0])
        inputs.append([s.strip() for s in steps])
    if not inputs or not any(inputs[0]):
        continue
    key = re.sub(r'[^a-z0-9]', '', name.group(1).lower())
    for prefix in ('grab', 'grind'):
        if key.startswith(prefix) and len(key) > len(prefix):
            key = key[len(prefix):]
    regular, goofy = inputs[0], inputs[1] if len(inputs) > 1 else inputs[0]
    # The Skatepedia does not keep a fixed order: the regular stance's input is the one whose
    # flick-it picture is named after the trick (Kickflip lists its own first, Hardflip second).
    def names(steps):
        return [re.sub(r'[^a-z0-9]', '', m.lower()) for s in steps for m in re.findall(r'FLICKIT_(\w+?)_RS', s)]
    exact = lambda steps: key in names(steps)
    near = lambda steps: any(key in n for n in names(steps))
    if (not exact(regular) and exact(goofy)) or (not near(regular) and near(goofy)):
        regular, goofy = goofy, regular
    entries.setdefault(key, (regular, goofy))

def literal(steps):
    return '{' + ', '.join('"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"' for s in steps) + '}'

width = max(len(steps) for pair in entries.values() for steps in pair)
lines = ['#pragma once',
         '// Generated by Extension/Modes/Tools/bake_skatepedia_inputs.py from skate.\'s Skatepedia entries',
         '// (gameplay/skatepedia/tricks/skatepediaentry_*): each trick\'s input steps for a regular and a goofy',
         '// stance, in the game\'s own markup. Do not edit by hand.',
         '#include <array>', '#include <string_view>', '',
         'namespace dingosdk::modes::skatepedia {',
         'struct Inputs {',
         '    std::string_view key; // the entry name, lower case, letters and digits, without "grab"/"grind"',
         f'    std::array<std::string_view, {width}> regular, goofy; // unused steps are empty',
         '};',
         f'inline constexpr std::array<Inputs, {len(entries)}> inputs{{{{']
for key in sorted(entries):
    regular, goofy = entries[key]
    lines.append(f'    {{"{key}", {literal(regular)}, {literal(goofy)}}},')
lines += ['}};', '} // namespace dingosdk::modes::skatepedia', '']
output.write_text('\n'.join(lines), encoding='utf-8', newline='\n')
print(f'{len(entries)} entries -> {output}')
